/** Preferencias persistentes: tema e idioma */
export const usePrefs = create(
  persist(
    (set, get) => ({
      theme: typeof document !== 'undefined' ? document.documentElement.dataset.theme || 'light' : 'light',
      lang: typeof document !== 'undefined' ? document.documentElement.lang || 'es' : 'es',
      setLang: (lang) => {
        document.documentElement.lang = lang;
        set({ lang });
      },
      toggleTheme: () => {
        const theme = get().theme === 'dark' ? 'light' : 'dark';
        document.documentElement.dataset.theme = theme;
        document.querySelector('meta[name="theme-color"]')?.setAttribute('content', theme === 'dark' ? '#0B1120' : '#FBF9F5');
        set({ theme });
      },
    }),
    { name: 'hangar-prefs' },
  ),
);

const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s);

/** t('clave', {vars}) para la UI · l({es,en}) para contenido del catálogo */
export function useI18n() {
  const lang = usePrefs((s) => s.lang);
  const t = (key, vars) => fill(dict[lang]?.[key] ?? dict.es[key] ?? key, vars);
  const l = (obj) => (obj && typeof obj === 'object' ? obj[lang] ?? obj.es ?? '' : obj ?? '');
  return { t, l, lang };
}

/** Para textos con <i> (énfasis en serif) */
export const html = (s) => ({ __html: s });
